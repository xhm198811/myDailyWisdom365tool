/** 时段问候前缀：早晨 / 上午 / 中午 / 下午 / 晚上 */
function timeGreeting(hour) {
  if (hour < 5) return '夜深了'
  if (hour < 9) return '早安'
  if (hour < 12) return '上午好'
  if (hour < 14) return '午安'
  if (hour < 18) return '下午好'
  if (hour < 23) return '晚上好'
  return '夜深了'
}

